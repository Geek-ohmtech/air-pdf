// 브라우저 시험 2: 탭, 입력란 채우기, 양식 안 글자 편집, 이미지 ↔ PDF, 용량 줄이기
import { createRequire } from 'node:module';
import fs from 'node:fs';
const { chromium } = createRequire(import.meta.url)('playwright');
const SHOT = process.env.SHOT || '/tmp';
const FX = new URL('./fixtures/', import.meta.url).pathname;
const base = 'http://localhost:4173/';
const b = await chromium.launch();
const page = await b.newPage({ viewport: { width: 1360, height: 860 }, acceptDownloads: true });
const errs = [];
page.on('pageerror', e => errs.push('pageerror ' + e.message));
page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
let fails = 0;
const ok = (c, m) => { console.log((c ? '  ✓ ' : '  ✗ ') + m); if (!c) fails++; };
await page.addInitScript(() => { delete window.showSaveFilePicker; delete window.showOpenFilePicker; });
const ev = (fn, arg) => page.evaluate(fn, arg);

console.log('탭');
await page.goto(base + '?file=fixtures/sample.pdf&file=fixtures/form.pdf&file=fixtures/xobject.pdf');
await page.waitForFunction(() => window.__app?.tabs?.length === 3 && document.querySelector('.page canvas.pg-base')?.width > 10, null, { timeout: 20000 });
ok(await page.locator('.tabbar .tab').count() === 3, '문서 3개가 탭으로 열림');
await page.locator('.tabbar .tab').nth(0).click();
await page.waitForTimeout(400);
ok(await ev(() => window.__app.doc.name) === 'sample.pdf', '탭 눌러 바꾸기');
await page.evaluate(() => window.__app.view.scrollToPage(3));
await page.keyboard.press('Control+Tab'); await page.waitForTimeout(300);
await page.keyboard.press('Control+Shift+Tab'); await page.waitForTimeout(400);
ok(await ev(() => window.__app.view.current) === 3, '탭마다 보던 쪽 기억');

console.log('입력란 채우기 (보기 모드)');
await page.locator('.tabbar .tab').nth(1).click();
await page.waitForSelector('.fld-text');
await page.locator('.fld-text').first().click();
await page.waitForSelector('input.fld-input');
await page.keyboard.type('홍길동 Kim');
await page.keyboard.press('Enter');
await page.waitForTimeout(500);
await page.locator('.fld-checkbox').click();
await page.waitForTimeout(400);
await page.locator('.fld-combo').click();
await page.waitForSelector('select.fld-input');
await page.selectOption('select.fld-input', '2');
await page.waitForTimeout(500);
await page.locator('.fld-text').nth(1).click();
await page.waitForSelector('textarea.fld-input');
await page.keyboard.type('여러 줄 메모 칸입니다. 길게 쓰면 자동으로 줄이 바뀌어 칸 안에 들어갑니다.');
await page.mouse.click(1200, 600);
await page.waitForTimeout(700);
const vals = await ev(async () => (await window.__app.engine.call('fields', [window.__app.doc.id, 0])).map(f => f.type === 'checkbox' ? f.checked : f.value));
ok(vals[0] === '홍길동 Kim' && vals[1] === true && vals[2] === 'Daegu' && vals[3].startsWith('여러 줄'), '값: ' + JSON.stringify(vals));
await page.waitForTimeout(400);
await page.screenshot({ path: SHOT + '/f1-form.png' });

console.log('양식 안 글자 편집');
await page.locator('.tabbar .tab').nth(2).click();
await page.waitForTimeout(400);
await page.click('.mode-b[data-m="edit"]');
await page.waitForSelector('.ribbon .rt');
await page.evaluate(() => { window.__app.setFit('page'); window.__app.view.scrollToPage(0); });
await page.waitForTimeout(500);
await page.click('.rt[data-tool="editText"]');
await page.waitForTimeout(600);
const pg = await page.locator('.page').first().boundingBox(); const z = await ev(() => window.__app.view.zoom);
await page.mouse.click(pg.x + 150 * z, pg.y + (842 - 636) * z);
await page.waitForSelector('textarea.ed-text');
const was = await page.inputValue('textarea.ed-text');
await page.fill('textarea.ed-text', '안녕하세요 양식');
await page.keyboard.press('Enter');
await page.waitForTimeout(1000);
const t1 = await ev(async () => (await window.__app.engine.call('textData', [window.__app.doc.id, 0])).text.replace(/\s+/g, ' '));
const t2 = await ev(async () => (await window.__app.engine.call('textData', [window.__app.doc.id, 1])).text.replace(/\s+/g, ' '));
ok(was === 'Hello Form' && t1.includes('안녕하세요 양식') && t2.includes('Hello Form'), `양식 글자 고침 (“${was}” → 1쪽: ${t1} / 2쪽: ${t2})`);
await page.screenshot({ path: SHOT + '/f2-xobject.png' });
await page.keyboard.press('Control+z'); await page.waitForTimeout(700);
ok((await ev(async () => (await window.__app.engine.call('textData', [window.__app.doc.id, 0])).text)).includes('Hello Form'), '되돌리기');
await page.click('.mode-b[data-m="view"]');

console.log('이미지 → PDF');
await page.click('.topbar .tb-group:last-child .tb:last-child');
const [fc] = await Promise.all([page.waitForEvent('filechooser'), page.click('.menu-item:has-text("이미지로 PDF 만들기")')]);
await fc.setFiles([FX + 'photo.jpg', FX + 'logo.png']);
await page.waitForSelector('.modal .suggest');
await page.locator('.modal .suggest .chk').nth(0).locator('input').uncheck(); // 보정 없이
await page.locator('.modal .suggest .chk').nth(1).locator('input').uncheck(); // OCR 없이
await page.click('.modal .btn.primary');
await page.waitForFunction(() => window.__app.tabs.length === 4, null, { timeout: 15000 });
ok(await ev(() => window.__app.doc.info.pageCount) === 2 && await ev(() => window.__app.doc.dirty), '이미지 2장 → 2쪽 새 PDF 탭');
await page.waitForTimeout(600);
await page.screenshot({ path: SHOT + '/f3-images.png' });

console.log('용량 줄이기');
await page.click('.topbar .tb-group:last-child .tb:last-child');
await page.click('.menu-item:has-text("PDF 용량 줄이기")');
await page.waitForSelector('.modal');
await page.click('.modal .btn.primary');
await page.waitForSelector('.modal .big-num', { timeout: 30000 });
const big = await page.textContent('.modal .big-num');
await page.screenshot({ path: SHOT + '/f4-compress.png' });
const m = /([\d.]+)(MB|KB) → ([\d.]+)(MB|KB)/.exec(big);
const kb = (v, u) => u === 'MB' ? v * 1024 : +v;
ok(m && kb(m[3], m[4]) < kb(m[1], m[2]) / 3, '용량: ' + big);
await page.click('.modal .btn:has-text("새 탭으로")');
await page.waitForFunction(() => window.__app.tabs.length === 5, null, { timeout: 10000 });
ok(true, '줄인 사본을 새 탭으로 엶');

console.log('쪽을 이미지로 내보내기');
await page.click('.topbar .tb-group:last-child .tb:last-child');
await page.click('.menu-item:has-text("이미지로 내보내기")');
await page.waitForSelector('.modal');
await page.selectOption('.modal select >> nth=0', 'all');
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('.modal .btn.primary')]);
const zp = SHOT + '/pages.zip'; await dl.saveAs(zp);
const zb = fs.readFileSync(zp);
ok(zb.readUInt32LE(0) === 0x04034b50 && zb.length > 20000, `ZIP 받음 (${(zb.length / 1024).toFixed(0)}KB)`);

console.log('탭 닫기');
const n0 = await ev(() => window.__app.tabs.length);
await page.locator('.tabbar .tab.on .tab-x').click();
await page.waitForSelector('.modal .btn.danger'); await page.click('.modal .btn.danger');
await page.waitForTimeout(400);
ok(await ev(() => window.__app.tabs.length) === n0 - 1, '저장 안 한 탭을 확인 후 닫음');

ok(errs.length === 0, '콘솔 오류 없음' + (errs.length ? ': ' + errs.slice(0, 4).join(' / ') : ''));
await b.close();
console.log(fails ? `\n실패 ${fails}건` : '\n모두 통과');
process.exit(fails ? 1 : 0);
